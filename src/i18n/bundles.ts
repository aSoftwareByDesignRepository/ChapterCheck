function assertBundleParity(a: Bundle, b: Bundle): void {
  const ak = new Set(Object.keys(a));
  for (const k of Object.keys(b)) {
    if (!ak.has(k)) throw new Error(`i18n: extra key in de: ${k}`);
  }
  for (const k of ak) {
    if (!(k in b)) throw new Error(`i18n: missing key in de: ${k}`);
  }
}

assertBundleParity(en, de);

export const bundles: Record<Locale, Bundle> = { en, de };

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? ""));
}
